import Foundation

/// 窗口口径的 SSOT。
///
/// 锚日曾经散在 CurveView 里,而风控页用的是服务端默认的全窗口 —— 两页对同一件事
/// 给出不同的答案(回撤 −11.92% vs −9.62%),而且**两个都对**,只是窗口不同。
/// 用户看到的却是「这 app 自己都对不上」。所以窗口只此一处。
///
/// ## 两个窗口,各有各的活(2026-08-29 二次订正)
///
/// | 窗口 | 谁用 | 为什么 |
/// |---|---|---|
/// | **锚日 2026-07-09** | 曲线(记分板) | 和博客那条已发布的折线可比。换锚 = 换了一个问题 |
/// | **全窗口(2025-01-02 起)** | 首屏 · 风控 | 风险统计要**最长的干净样本** |
///
/// 一度把风控页也统一到锚日,那是当时的两害相权:全窗口只有 53 个 session,
/// 而且里面有 18 天资金流未记录。**这两条前提今天都没了** —— 序列补到 400 个
/// session、资金流全窗口逐日已知,再拿 35 个链接去算年化和 Sharpe 就是白白扔掉
/// 九成样本(n=35 的 Sharpe 标准误 ±0.80,n=399 是 ±0.08)。
///
/// ⚠ **换窗口不是为了让结论变好看。** 回撤硬约束在**两个窗口下都是破的**
/// (全窗口 我 −32.11% vs 加权基准 −21.72%;锚日 −9.62% vs −7.17%),
/// 挑一个能让破裂消失的窗口是作弊 —— 这里没有那样的窗口可挑,也不去挑。
enum DeskWindow {
    /// 记分板锚日,与博客 `race_series.py` 的 `RACE_ANCHOR` 同一个日子。
    /// 改它 = 换了一个问题(那边注释写着「写死,禁改」,背后有一次真事故)。
    static let raceAnchor = "2026-07-09"

    /// 拼给服务端的查询串(记分板口径)。
    static func startQuery(_ anchored: Bool = true) -> String {
        anchored ? "?start=\(raceAnchor)" : ""
    }

    /// 风险统计的窗口 = 全窗口(服务端默认)。空串,让服务端用它自己的起点 ——
    /// 客户端写死一个起点就成了第二处口径,而服务端补数据时它不会跟着走。
    static let riskQuery = ""
}
